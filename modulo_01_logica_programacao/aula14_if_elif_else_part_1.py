# Operações condicionais 
entrada = input('Voce quer "entrar" ou "sair"? ')

if entrada == 'entrar':
    print('Voce entrou no sistema.')
elif entrada == 'sair':
    print('Voce saiu do sistema.')
else:
    print('Opção invalida, digite "entrar" ou "sair"')
